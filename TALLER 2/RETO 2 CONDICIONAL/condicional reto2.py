# solicitar el numero al usuario y convertir la entrada a un numero entero (int) 
# esto declararia la variable numero y la cojnveirte en entero int el input es para guardar y leer el numero del cliente

numero = int(input("Ingresa un número entero (positivo o negativo): "))

# el operador modulo (%) para la Decision (if/else)
# el operador %  el residuo de la division.
# si el residuo de dividir entre 2 es 0, el número es par. el if seria lo mismo que el si en el flowgorinthm
if numero % 2 == 0:
    # Rama de decision verdadera (Verdadero)
    print(f"El número {numero} es par.")
else:
    # Rama de decision (Falso)
    print(f"El número {numero} es impar.")

